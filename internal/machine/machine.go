// Package machine describes how one machine is set up: what it needs to
// boot and swap the way it was installed. The installer writes it from the
// plan and arcus machine from the running system; both go through Files,
// so a machine installed by arcus and one adopted later match.
package machine

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// Dir holds machine-local modules; arcus loads them next to the user's.
const Dir = "etc/arcus/modules"

// Name is the module that describes the machine.
const Name = "machine"

// Facts are what the module is generated from.
type Facts struct {
	UEFI        bool
	Kernels     []string // kernel packages
	Firmware    bool     // linux-firmware
	GRUB        bool
	Filesystems []string // types in use: btrfs, ext4, vfat, ...
	CPU         string   // vendor_id from /proc/cpuinfo
	GPUs        []string // PCI vendor IDs of the display controllers
	Zram        bool     // swap in compressed RAM
	SSD         bool     // a disk is solid state, so fstrim.timer trims it
}

var (
	// Kernels arcus knows as kernel packages.
	Kernels   = []string{"linux", "linux-lts", "linux-zen", "linux-hardened"}
	fsTools   = map[string]string{"btrfs": "btrfs-progs", "ext2": "e2fsprogs", "ext3": "e2fsprogs", "ext4": "e2fsprogs", "xfs": "xfsprogs", "vfat": "dosfstools", "f2fs": "f2fs-tools", "exfat": "exfatprogs"}
	microcode = map[string]string{"AuthenticAMD": "amd-ucode", "GenuineIntel": "intel-ucode"}
	// Graphics drivers by PCI vendor ID. NVIDIA's depend on the kernels.
	gpuDrivers = map[string][]string{"0x1002": {"mesa", "vulkan-radeon"}, "0x8086": {"mesa", "vulkan-intel", "intel-media-driver"}}
	// nvidiaModules are NVIDIA's prebuilt open kernel modules; other
	// kernels get nvidia-open-dkms, which builds them against the headers.
	nvidiaModules = map[string]string{"linux": "nvidia-open", "linux-lts": "nvidia-open-lts"}
)

// NVIDIA is the PCI vendor ID of NVIDIA.
const NVIDIA = "0x10de"

// Packages are what the machine needs, in a fixed order.
func (f Facts) Packages() []string {
	pkgs := slices.Sorted(slices.Values(f.Kernels))
	if f.Firmware {
		pkgs = append(pkgs, "linux-firmware")
	}
	if m := microcode[f.CPU]; m != "" {
		pkgs = append(pkgs, m)
	}
	add := func(names ...string) {
		for _, n := range names {
			if !slices.Contains(pkgs, n) {
				pkgs = append(pkgs, n)
			}
		}
	}
	for _, gpu := range slices.Sorted(slices.Values(f.GPUs)) {
		add(gpuDrivers[gpu]...)
		if gpu != NVIDIA {
			continue
		}
		for _, k := range slices.Sorted(slices.Values(f.Kernels)) {
			if m := nvidiaModules[k]; m != "" {
				add(m)
			} else {
				add("nvidia-open-dkms", k+"-headers")
			}
		}
		add("nvidia-utils")
	}
	if f.GRUB {
		pkgs = append(pkgs, "grub")
		if f.UEFI {
			pkgs = append(pkgs, "efibootmgr")
		}
	}
	tools := map[string]bool{}
	for _, fs := range f.Filesystems {
		if t := fsTools[fs]; t != "" {
			tools[t] = true
		}
	}
	pkgs = append(pkgs, slices.Sorted(maps.Keys(tools))...)
	if f.Zram {
		pkgs = append(pkgs, "zram-generator")
	}
	return pkgs
}

// Files returns the module's files, keyed by path inside the module.
func (f Facts) Files() map[string]string {
	firmware := "BIOS"
	if f.UEFI {
		firmware = "UEFI"
	}
	files := map[string]string{"module.toml": fmt.Sprintf(`# Generated by arcus for this machine (%s): what it needs to boot and swap
# the way it is set up. 'arcus machine' writes it again from the system.
description = "This machine: kernel, firmware, microcode, graphics drivers, bootloader, filesystem tools, swap, SSD trim"
category    = "system"

[packages]
pacman = ["%s"]
`, firmware, strings.Join(f.Packages(), `", "`))}
	if f.SSD {
		files["module.toml"] += "\n[units]\nsystem = [\"fstrim.timer\"]   # trims the SSDs weekly\nnow    = true\n"
	}
	if f.Zram {
		files["system/etc/systemd/zram-generator.conf"] = "# Half the RAM, at most 8 GiB, compressed with zstd.\n[zram0]\nzram-size = min(ram / 2, 8192)\ncompression-algorithm = zstd\n"
		files["system/etc/sysctl.d/99-zram.conf"] = "# Swapping to compressed RAM is cheap, so swap earlier and one page at a\n# time (values from the Arch wiki, \"zram\").\nvm.swappiness = 180\nvm.watermark_boost_factor = 0\nvm.watermark_scale_factor = 125\nvm.page-cluster = 0\n"
	}
	return files
}

// Hash identifies the module's files.
func (f Facts) Hash() string {
	files := f.Files()
	h := sha256.New()
	for _, path := range slices.Sorted(maps.Keys(files)) {
		fmt.Fprintf(h, "%s\x00%s\x00", path, files[path])
	}
	return hex.EncodeToString(h.Sum(nil))
}

// Write writes the module into dir, replacing whatever was there.
func (f Facts) Write(dir string) error {
	tmp := dir + ".new"
	if err := os.RemoveAll(tmp); err != nil {
		return err
	}
	for path, content := range f.Files() {
		file := filepath.Join(tmp, path)
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
			return err
		}
	}
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	return os.Rename(tmp, dir)
}

// CPU reads the CPU vendor from cpuinfo.
func CPU(cpuinfo string) string {
	f, err := os.Open(cpuinfo)
	if err != nil {
		return ""
	}
	defer f.Close()
	s := bufio.NewScanner(f)
	for s.Scan() {
		if key, value, ok := strings.Cut(s.Text(), ":"); ok && strings.TrimSpace(key) == "vendor_id" {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

// GPUs reads the PCI vendor IDs of the display controllers below root.
// NVIDIA's open kernel modules need a Turing (GTX 16, RTX 20) or newer card.
func GPUs(root string) []string {
	var gpus []string
	devices, _ := filepath.Glob(filepath.Join(root, "sys/bus/pci/devices/*"))
	for _, dev := range devices {
		class, _ := os.ReadFile(filepath.Join(dev, "class"))
		vendor, _ := os.ReadFile(filepath.Join(dev, "vendor"))
		if v := strings.TrimSpace(string(vendor)); strings.HasPrefix(string(class), "0x03") && !slices.Contains(gpus, v) {
			gpus = append(gpus, v)
		}
	}
	return gpus
}

// SSD reports whether a disk below root is solid state: a non-removable,
// non-rotational block device with a device behind it, which leaves out
// loop, zram and device-mapper devices.
func SSD(root string) bool {
	disks, _ := filepath.Glob(filepath.Join(root, "sys/block/*"))
	for _, disk := range disks {
		if _, err := os.Stat(filepath.Join(disk, "device")); err != nil {
			continue
		}
		removable, _ := os.ReadFile(filepath.Join(disk, "removable"))
		rotational, _ := os.ReadFile(filepath.Join(disk, "queue/rotational"))
		if strings.TrimSpace(string(removable)) == "0" && strings.TrimSpace(string(rotational)) == "0" {
			return true
		}
	}
	return false
}

// Detect reads the facts of the running system below root; installed are
// the installed packages.
func Detect(root string, installed map[string]bool) Facts {
	_, err := os.Stat(filepath.Join(root, "sys/firmware/efi"))
	f := Facts{
		UEFI:     err == nil,
		Firmware: installed["linux-firmware"],
		GRUB:     installed["grub"],
		CPU:      CPU(filepath.Join(root, "proc/cpuinfo")),
		GPUs:     GPUs(root),
		Zram:     installed["zram-generator"],
		SSD:      SSD(root),
	}
	for _, k := range Kernels {
		if installed[k] {
			f.Kernels = append(f.Kernels, k)
		}
	}
	// Filesystems on block devices; /proc/self/mounts lists each mount
	// as "device mountpoint type options 0 0".
	if data, err := os.ReadFile(filepath.Join(root, "proc/self/mounts")); err == nil {
		for line := range strings.Lines(string(data)) {
			fields := strings.Fields(line)
			if len(fields) > 2 && strings.HasPrefix(fields[0], "/dev/") && !slices.Contains(f.Filesystems, fields[2]) {
				f.Filesystems = append(f.Filesystems, fields[2])
			}
		}
	}
	slices.Sort(f.Filesystems)
	return f
}
